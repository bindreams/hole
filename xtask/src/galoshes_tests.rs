use crate::galoshes::cache_sidecar_name;
use crate::target::host_target_triple;

#[skuld::test]
fn cache_sidecar_name_matches_host_triple() {
    // Must match exactly what Tauri appends to the externalBin path, or the
    // macOS DMG bundles nothing. Assert the full name, not just a prefix.
    let exe = if cfg!(target_os = "windows") { ".exe" } else { "" };
    let expected = format!("galoshes-{}{exe}", host_target_triple());
    assert_eq!(cache_sidecar_name(), expected);
}

use crate::galoshes::build_args;

#[skuld::test]
fn crash_dumps_opt_in_adds_the_feature_only_for_windows() {
    // `.dmp` is a Windows-only branch: `minidump-writer` is declared under
    // `[target.'cfg(windows)'.dependencies]`, and since #842 the macOS
    // `on_crash` has no dump branch at all (crates/tombstone/src/crash.rs
    // module doc).
    assert_eq!(
        build_args(true, true),
        vec![
            "build",
            "--release",
            "-p",
            "galoshes",
            "--features",
            "galoshes/crash-dumps"
        ]
    );
}

#[skuld::test]
fn crash_dumps_opt_in_is_a_no_op_off_windows() {
    // Not merely "changes no behaviour" — it must produce the IDENTICAL
    // command line. A different feature set is a different cargo
    // fingerprint, so `cargo xtask run hole` on darwin paid a full release
    // rebuild of galoshes + tombstone for a feature that links nothing.
    assert_eq!(build_args(true, false), build_args(false, false));
    assert_eq!(build_args(true, false), vec!["build", "--release", "-p", "galoshes"]);
}

use crate::galoshes::fetch_crates;

/// A dependency-free package with a lockfile that matches its manifest, so `cargo fetch` needs no network.
fn scratch_package(dir: &std::path::Path) -> std::path::PathBuf {
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(dir.join("src").join("lib.rs"), "").unwrap();
    std::fs::write(
        dir.join("Cargo.toml"),
        "[package]\nname = \"scratch\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"scratch\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    dir.join("Cargo.lock")
}

#[skuld::test]
fn fetch_crates_accepts_a_lockfile_that_matches_the_manifest() {
    let dir = tempfile::tempdir().unwrap();
    let lock = scratch_package(dir.path());
    let before = std::fs::read(&lock).unwrap();

    fetch_crates(dir.path()).unwrap();

    assert_eq!(std::fs::read(&lock).unwrap(), before);
}

/// A stale lock is the same on every attempt, so it must fail on the first (the old `--locked` fetch
/// under `until_ok` retried it until the step timeout), and leave the lock as the developer wrote it.
#[skuld::test]
fn fetch_crates_fails_at_once_on_a_stale_lockfile_and_leaves_it_untouched() {
    let dir = tempfile::tempdir().unwrap();
    let lock = scratch_package(dir.path());
    std::fs::write(
        dir.path().join("Cargo.toml"),
        "[package]\nname = \"scratch\"\nversion = \"0.2.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    let before = std::fs::read(&lock).unwrap();

    let err = fetch_crates(dir.path()).unwrap_err();

    assert!(
        format!("{err:#}").contains("is out of date"),
        "unexpected error: {err:#}"
    );
    assert_eq!(std::fs::read(&lock).unwrap(), before);
}
